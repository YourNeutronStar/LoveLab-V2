/**
 * Build the standalone story as a plain JS string for local file:// usage.
 * No dependencies or npm install required. Run: node tools/build.mjs
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname, resolve} from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=name=>readFileSync(resolve(root,name),'utf8');
const html=read('src/story.html');
const css=read('src/story.css');
const js=read('src/story.js');
const bundled=html
  .replace('<!-- STORY_CSS -->',`<style>\n${css}\n</style>`)
  .replace('<!-- STORY_JS -->',`<script>\n${js.replaceAll('</script','<\\/script')}\n</script>`);
if(bundled.includes('<!-- STORY_'))throw Error('Build placeholders missing');
writeFileSync(resolve(root,'js/story-template.js'),
  '/* Generated by node tools/build.mjs; edit src/story.* instead. */\n'+
  'window.LoveLabStoryTemplate = '+JSON.stringify(bundled)+';\n','utf8');
console.log('✓ Built js/story-template.js ('+bundled.length+' bytes)');
